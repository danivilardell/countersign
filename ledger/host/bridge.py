#!/usr/bin/env python3
"""Countersign host bridge for Ledger devices.

A Ledger has no network, so this script plays the role of the phone's app
shell: it talks to the Countersign service with the device bearer token and
relays challenges and request messages to the Ledger app over USB (or TCP
for the Speculos emulator). It is the untrusted platform of the I-HITL
model: it never holds a signing key, and the device shows and signs the
exact message bytes it receives, so nothing here can approve on the
human's behalf.

Commands mirror the mobile apps' screens:
  provision         Once per device, from the dashboard: generate the endorsement
                    key and capture the device's certificate chain (see below)
  enroll            Enroll this device (confirm on the Ledger)
  status            Enrollment status
  pending           Pending approvals
  approve REF       Review request REF on the Ledger and submit the signature
  decline REF       Decline request REF
  watch             Poll for new pending approvals every 3 seconds

Configuration (environment variables):
  COUNTERSIGN_SERVER_URL        e.g. https://your-server.example.com or http://127.0.0.1:8002
  COUNTERSIGN_DEVICE_TOKEN      the device token (COUNTERSIGN_API_TOKEN of the service), never the admin token
  COUNTERSIGN_LEDGER_TRANSPORT  hid (default) or tcp:127.0.0.1:9999 for Speculos
  COUNTERSIGN_LEDGER_STATE      path of the file holding this device's id and chain (default ~/.countersign/ledger.json)

Provisioning: a Ledger's endorsement key is generated by the OS dashboard
(not by the app) and vouched for by a chain the dashboard presents during the
secure-channel handshake: Ledger's published root signs the device key
(issuer certificate), and the device key signs the new endorsement key. The
bridge captures that chain, commits the device's signature as the slot's
certificate, and submits the chain at enrollment so the service verifies
root -> device -> endorsement key itself; nothing here needs a custom CA or
a secret, and the user accepts the connection on the device.
"""

from __future__ import annotations

import argparse
import base64
import datetime as dt
import json
import os
import sys
import time
from dataclasses import dataclass
from pathlib import Path

import httpx

CLA = 0xE0
INS_GET_VERSION = 0x03
INS_ENROLL = 0x10
INS_APPROVE = 0x20
SW_OK = 0x9000
SW_DENY = 0x6985
# The SDK answers this while the app is still showing a status page (about
# two seconds after an approval); the app accepts the command once it is back home.
SW_BUSY = 0x6901
SW_ENDORSEMENT_UNAVAILABLE = 0xB010
PUBLIC_KEY_LENGTH = 65
CODE_HASH_LENGTH = 32
CHALLENGE_LENGTH = 32
ISSUER_CERTIFICATE_ROLE = b"\x02"
DEVICE_CERTIFICATE_ROLE = b"\xff"
LEDGER_ROOT_FILE = Path(__file__).resolve().parents[2] / "attestation_roots" / "ledger_root_of_trust.txt"
# One APDU carries at most 255 data bytes; the app never chunks a message.
MAX_MESSAGE_BYTES = 255
POLL_SECONDS = 3


# --- APDU framing (pure functions, unit-tested in tests/test_ledger_bridge.py) ---


def build_apdu(ins: int, data: bytes = b"") -> bytes:
    if len(data) > 255:
        raise ValueError("APDU data must be at most 255 bytes")
    return bytes([CLA, ins, 0x00, 0x00, len(data)]) + data


@dataclass
class EnrollmentEvidence:
    public_key: bytes
    code_hash: bytes
    owner_certificate: bytes
    challenge_signature: bytes

    def to_request_body(self, chain: "DeviceChain | None" = None) -> dict[str, str]:
        b64 = lambda value: base64.b64encode(value).decode("ascii")  # noqa: E731
        body = {
            "endorsement_public_key_b64": b64(self.public_key),
            "code_hash_b64": b64(self.code_hash),
            "owner_certificate_b64": b64(self.owner_certificate),
            "challenge_signature_b64": b64(self.challenge_signature),
        }
        if chain is not None:
            body["device_public_key_b64"] = b64(chain.device_public_key)
            body["issuer_certificate_header_b64"] = b64(chain.issuer_certificate_header)
            body["issuer_signature_b64"] = b64(chain.issuer_signature)
        return body


@dataclass
class DeviceChain:
    """Captured at provisioning from the dashboard's secure-channel handshake."""

    device_public_key: bytes
    issuer_certificate_header: bytes
    issuer_signature: bytes
    endorsement_public_key: bytes

    def to_json(self) -> dict[str, str]:
        return {k: v.hex() for k, v in self.__dict__.items()}

    @classmethod
    def from_json(cls, data: dict[str, str]) -> "DeviceChain":
        return cls(**{k: bytes.fromhex(data[k]) for k in ("device_public_key", "issuer_certificate_header", "issuer_signature", "endorsement_public_key")})


def parse_dashboard_certificate(data: bytes) -> tuple[bytes, bytes, bytes]:
    """GET_CERTIFICATE response: len || header || len || public key || len || signature."""
    fields = []
    offset = 0
    for _ in range(3):
        if offset >= len(data):
            raise ValueError("certificate is too short")
        length, offset = data[offset], offset + 1
        fields.append(data[offset : offset + length])
        offset += length
    if offset != len(data) or len(fields[1]) != PUBLIC_KEY_LENGTH:
        raise ValueError("malformed dashboard certificate")
    return fields[0], fields[1], fields[2]


def parse_endorse_start_response(data: bytes) -> tuple[bytes, bytes]:
    """ENDORSE_SET_START response: endorsement public key (65) || device signature (DER)."""
    public_key, signature = data[:PUBLIC_KEY_LENGTH], data[PUBLIC_KEY_LENGTH:]
    if len(public_key) != PUBLIC_KEY_LENGTH or public_key[0] != 0x04 or not signature:
        raise ValueError("malformed endorsement response")
    return bytes(public_key), bytes(signature)


def verify_chain_locally(chain: DeviceChain, device_signature: bytes, roots_file: Path = LEDGER_ROOT_FILE) -> str:
    """Same check the service makes, as a courtesy before anything is committed."""
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import ec

    def key(raw: bytes):
        return ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256K1(), raw)

    try:
        key(chain.device_public_key).verify(
            device_signature, DEVICE_CERTIFICATE_ROLE + chain.endorsement_public_key, ec.ECDSA(hashes.SHA256())
        )
    except (InvalidSignature, ValueError):
        return "the device did not sign the endorsement key it returned"
    if not roots_file.exists():
        return f"root file {roots_file} not found; the service will verify the issuer certificate"
    roots = [bytes.fromhex(line.split("#", 1)[0].strip()) for line in roots_file.read_text().splitlines()]
    issued = ISSUER_CERTIFICATE_ROLE + chain.issuer_certificate_header + chain.device_public_key
    for raw in (r for r in roots if r):
        try:
            key(raw).verify(chain.issuer_signature, issued, ec.ECDSA(hashes.SHA256()))
            return "ok"
        except (InvalidSignature, ValueError):
            continue
    return "issuer certificate does not verify under Ledger's published root"


def parse_enroll_response(data: bytes) -> EnrollmentEvidence:
    """public_key(65) || code_hash(32) || cert_len(1) || cert || sig_len(1) || sig"""
    offset = 0
    public_key = data[offset : offset + PUBLIC_KEY_LENGTH]
    offset += PUBLIC_KEY_LENGTH
    code_hash = data[offset : offset + CODE_HASH_LENGTH]
    offset += CODE_HASH_LENGTH
    if len(public_key) != PUBLIC_KEY_LENGTH or len(code_hash) != CODE_HASH_LENGTH or offset >= len(data):
        raise ValueError("enrollment response is too short")
    cert_len, offset = data[offset], offset + 1
    certificate = data[offset : offset + cert_len]
    offset += cert_len
    if len(certificate) != cert_len or offset >= len(data):
        raise ValueError("enrollment response has an inconsistent certificate length")
    sig_len, offset = data[offset], offset + 1
    signature = data[offset : offset + sig_len]
    offset += sig_len
    if len(signature) != sig_len or offset != len(data):
        raise ValueError("enrollment response has an inconsistent signature length")
    return EnrollmentEvidence(public_key, code_hash, certificate, signature)


def message_fits(message: str) -> bool:
    return 0 < len(message.encode("utf-8")) <= MAX_MESSAGE_BYTES


def parse_expiry(value: str) -> dt.datetime:
    return dt.datetime.fromisoformat(value.replace("Z", "+00:00"))


def is_expired(approval: dict, now: dt.datetime | None = None) -> bool:
    return parse_expiry(approval["expires_at"]) <= (now or dt.datetime.now(dt.timezone.utc))


# --- device and service clients ---


class DeviceError(Exception):
    def __init__(self, sw: int):
        super().__init__(f"device returned status 0x{sw:04X}")
        self.sw = sw


class Device:
    """Thin wrapper over ledgercomm: HID to a real device, TCP to Speculos."""

    def __init__(self, transport_spec: str):
        from ledgercomm import Transport

        if transport_spec == "hid":
            self._transport = Transport(interface="hid")
        elif transport_spec.startswith("tcp:"):
            _, host, port = transport_spec.split(":")
            self._transport = Transport(interface="tcp", server=host, port=int(port))
        else:
            raise SystemExit("COUNTERSIGN_LEDGER_TRANSPORT must be 'hid' or 'tcp:<host>:<port>'")

    def exchange(self, ins: int, data: bytes = b"") -> bytes:
        for attempt in range(5):
            sw, response = self._transport.exchange_raw(build_apdu(ins, data))
            if sw != SW_BUSY:
                break
            time.sleep(1)
        if sw != SW_OK:
            raise DeviceError(sw)
        return bytes(response)

    def close(self) -> None:
        self._transport.close()


class ServiceError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status


class Service:
    """Device-scoped client of the Countersign service (service/app.py)."""

    def __init__(self, base_url: str, token: str):
        self._client = httpx.Client(
            base_url=base_url.rstrip("/"),
            headers={"Authorization": f"Bearer {token}", "User-Agent": "Countersign-Ledger-bridge/0.1"},
            timeout=15.0,
        )

    def _request(self, method: str, path: str, **kwargs):
        try:
            response = self._client.request(method, path, **kwargs)
        except httpx.HTTPError as exc:
            raise ServiceError(0, f"Could not reach the service. Check your connection. ({exc})") from None
        if response.status_code >= 400:
            try:
                detail = response.json().get("detail")
            except ValueError:
                detail = None
            if isinstance(detail, dict) and "reasons" in detail:
                detail = "\n".join(detail["reasons"])
            raise ServiceError(response.status_code, str(detail or f"HTTP {response.status_code}"))
        return response.json()

    def begin_enrollment(self) -> dict:
        return self._request("POST", "/v1/enroll/begin", json={"platform": "ledger"})

    def submit_endorsement(self, enrollment_id: str, evidence: EnrollmentEvidence, chain: DeviceChain | None = None) -> dict:
        return self._request("POST", f"/v1/enroll/{enrollment_id}/endorsement", json=evidence.to_request_body(chain))

    def enrollment_status(self, device_id: str) -> dict:
        return self._request("GET", f"/v1/enrollments/{device_id}")

    def pending_approvals(self, device_id: str) -> list[dict]:
        return self._request("GET", "/v1/approvals", params={"device_id": device_id})

    def get_approval(self, ref: str) -> dict:
        return self._request("GET", f"/v1/approvals/{ref}")

    def complete_approval(self, ref: str, signature: bytes) -> dict:
        body = {"signature_b64": base64.b64encode(signature).decode("ascii")}
        return self._request("POST", f"/v1/approvals/{ref}/complete", json=body)

    def decline_approval(self, ref: str) -> dict:
        return self._request("POST", f"/v1/approvals/{ref}/decline")


# --- local state: the server-issued device id, like DeviceState.kt / UserDefaults ---


class State:
    def __init__(self, path: Path):
        self.path = path

    def _read(self) -> dict:
        try:
            return json.loads(self.path.read_text())
        except (OSError, ValueError):
            return {}

    def _write(self, data: dict) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps(data))

    def device_id(self) -> str | None:
        return self._read().get("device_id")

    def chain(self) -> DeviceChain | None:
        data = self._read().get("chain")
        return DeviceChain.from_json(data) if data else None

    def save(self, device_id: str) -> None:
        self._write({**self._read(), "device_id": device_id})

    def save_chain(self, chain: DeviceChain) -> None:
        # A new endorsement key means a new identity: forget the old device_id.
        self._write({"chain": chain.to_json()})

    def clear(self) -> None:
        data = self._read()
        data.pop("device_id", None)
        if data:
            self._write(data)
        else:
            try:
                self.path.unlink()
            except FileNotFoundError:
                pass


# --- commands ---


@dataclass
class Context:
    service: Service
    state: State
    transport_spec: str

    def device(self) -> Device:
        return Device(self.transport_spec)

    def require_device_id(self) -> str:
        device_id = self.state.device_id()
        if device_id is None:
            raise SystemExit("Not enrolled yet. Run: bridge.py enroll")
        return device_id


def cmd_provision(ctx: Context) -> None:
    """Dashboard side (Countersign app closed): capture the device chain and
    generate the slot-1 endorsement key. Replaces any existing slot-1 key."""
    from ledgerwallet.client import LedgerClient
    from ledgerwallet.crypto.ecc import PrivateKey
    from ledgerwallet.simpleserver import SimpleServer
    from ledgerwallet.utils import LedgerIns

    class CapturingServer(SimpleServer):
        def send_certificate_chain(self, chain):
            self.captured = list(chain)
            return super().send_certificate_chain(chain)

    if ctx.transport_spec != "hid":
        raise SystemExit("Provisioning talks to the device dashboard over USB; Speculos is pre-provisioned.")
    print("Unlock the Ledger and stay on the dashboard. Accept the connection prompt if it appears...")
    client = LedgerClient(private_key=PrivateKey().serialize())  # throwaway host key, no custom CA
    server = CapturingServer(client.private_key)
    try:
        client.authenticate(server)
        header, device_public_key, issuer_signature = parse_dashboard_certificate(bytes(server.captured[0]))
        endorsement_public_key, device_signature = parse_endorse_start_response(
            bytes(client.apdu_exchange(LedgerIns.ENDORSE_SET_START, p1=1))
        )
        chain = DeviceChain(device_public_key, header, issuer_signature, endorsement_public_key)
        verdict = verify_chain_locally(chain, device_signature)
        if verdict != "ok":
            print(f"Warning: {verdict}")
        # The slot's certificate is the device's own signature over the key.
        client.apdu_exchange(LedgerIns.ENDORSE_SET_COMMIT, device_signature)
    finally:
        client.close()
    ctx.state.save_chain(chain)
    print(f"Device public key:      {device_public_key.hex()}")
    print(f"Endorsement public key: {endorsement_public_key.hex()}")
    print(f"Issuer certificate:     {verdict if verdict == 'ok' else 'unverified'} (Ledger root of trust)")
    print("Provisioned. Open the Countersign app on the device and run `bridge.py enroll`.")


def cmd_enroll(ctx: Context) -> None:
    if ctx.state.device_id() is not None:
        raise SystemExit("Already enrolled. Run `bridge.py status`, or delete the state file to enroll again.")
    chain = ctx.state.chain()
    begin = ctx.service.begin_enrollment()
    challenge = base64.b64decode(begin["challenge_b64"])
    if len(challenge) != CHALLENGE_LENGTH:
        raise SystemExit("The server returned an invalid attestation challenge.")
    print("Confirm the enrollment on the Ledger...")
    device = ctx.device()
    try:
        try:
            evidence = parse_enroll_response(device.exchange(INS_ENROLL, challenge))
        except DeviceError as error:
            if error.sw == SW_DENY:
                raise SystemExit("Cancelled on the device. Nothing was signed.") from None
            if error.sw == SW_ENDORSEMENT_UNAVAILABLE:
                raise SystemExit("The device has no endorsement key. Run ledger/host/endorse.py setup first.") from None
            raise SystemExit(str(error)) from None
    finally:
        device.close()
    print(f"Endorsement public key: {evidence.public_key.hex()}")
    print(f"Code hash (pin as COUNTERSIGN_LEDGER_CODE_HASH): {evidence.code_hash.hex()}")
    print(f"Certificate: {evidence.owner_certificate.hex()}")
    if chain is not None and chain.endorsement_public_key != evidence.public_key:
        raise SystemExit("The app reports a different endorsement key than the one provisioned. Run `bridge.py provision` again.")
    result = ctx.service.submit_endorsement(begin["enrollment_id"], evidence, chain)
    ctx.state.save(result["device_id"])
    print(f"Device ID: {result['device_id']}")
    print("Technical verification succeeded. Enrollment is pending administrator approval.")


def _status(ctx: Context, device_id: str) -> str | None:
    try:
        return ctx.service.enrollment_status(device_id)["status"]
    except ServiceError as error:
        if error.status == 404:
            ctx.state.clear()
            print("Device not recognized. Please enroll again.")
            return None
        raise


def cmd_status(ctx: Context) -> None:
    device_id = ctx.require_device_id()
    status = _status(ctx, device_id)
    if status == "approved":
        print(f"Enrolled: {device_id[:12]}...")
    elif status == "pending_manual_approval":
        print(f"Pending administrator approval\n{device_id[:12]}...")
    elif status is not None:
        print(f"Enrollment unavailable ({status}). Check with your administrator.")


def _print_pending(approvals: list[dict]) -> None:
    if not approvals:
        print("Nothing pending right now.")
    for approval in approvals:
        expiry = parse_expiry(approval["expires_at"]).astimezone().strftime("%b %d, %Y %H:%M")
        label = "Expired" if is_expired(approval) else "Expires"
        print(f"#{approval['ref']}  {approval['message']}\n    {label} {expiry}")


def cmd_pending(ctx: Context) -> None:
    device_id = ctx.require_device_id()
    if _status(ctx, device_id) != "approved":
        print("Pending administrator approval.")
        return
    _print_pending(ctx.service.pending_approvals(device_id))


def cmd_watch(ctx: Context) -> None:
    device_id = ctx.require_device_id()
    seen: set[str] = set()
    print("Watching for pending approvals (Ctrl-C to stop)...")
    while True:
        status = _status(ctx, device_id)
        if status is None:
            return
        if status == "approved":
            fresh = [a for a in ctx.service.pending_approvals(device_id) if a["ref"] not in seen]
            if fresh:
                _print_pending(fresh)
                seen.update(a["ref"] for a in fresh)
        time.sleep(POLL_SECONDS)


def cmd_approve(ctx: Context, ref: str) -> None:
    ctx.require_device_id()
    approval = ctx.service.get_approval(ref)
    if approval["status"] != "pending":
        raise SystemExit(f"No longer pending ({approval['status']}). Refresh the list.")
    if is_expired(approval):
        raise SystemExit("This request has expired.")
    message: str = approval["message"]
    if not message_fits(message):
        raise SystemExit(f"This request is longer than {MAX_MESSAGE_BYTES} bytes and cannot be shown on a Ledger.")
    print(f"Review on the Ledger: {message}")
    device = ctx.device()
    try:
        try:
            # The device signs exactly these UTF-8 bytes (plus the OS-appended code hash).
            signature = device.exchange(INS_APPROVE, message.encode("utf-8"))
        except DeviceError as error:
            if error.sw == SW_DENY:
                result = ctx.service.decline_approval(ref)
                print("Declined" if result["status"] == "declined" else f"Status: {result['status']}")
                return
            raise SystemExit(f"Nothing was signed. {error}") from None
    finally:
        device.close()
    if is_expired(approval):
        raise SystemExit("Expired during authentication. Nothing was submitted.")
    result = ctx.service.complete_approval(ref, signature)
    if result["status"] == "approved":
        print("Approved")
    else:
        reasons = "\n".join(result.get("reasons", []))
        raise SystemExit("Approval verification failed." + (f"\n{reasons}" if reasons else ""))


def cmd_decline(ctx: Context, ref: str) -> None:
    ctx.require_device_id()
    approval = ctx.service.get_approval(ref)
    if approval["status"] != "pending":
        raise SystemExit(f"No longer pending ({approval['status']}). Refresh the list.")
    result = ctx.service.decline_approval(ref)
    print("Declined" if result["status"] == "declined" else "Could not decline this request.")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Countersign host bridge for Ledger devices.")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("provision", "enroll", "status", "pending", "watch"):
        sub.add_parser(name)
    sub.add_parser("approve").add_argument("ref")
    sub.add_parser("decline").add_argument("ref")
    args = parser.parse_args(argv)

    server_url = os.environ.get("COUNTERSIGN_SERVER_URL", "")
    token = os.environ.get("COUNTERSIGN_DEVICE_TOKEN", "")
    if not server_url or not token:
        raise SystemExit("Set COUNTERSIGN_SERVER_URL and COUNTERSIGN_DEVICE_TOKEN (the device token, never the admin token).")
    ctx = Context(
        service=Service(server_url, token),
        state=State(Path(os.environ.get("COUNTERSIGN_LEDGER_STATE", "~/.countersign/ledger.json")).expanduser()),
        transport_spec=os.environ.get("COUNTERSIGN_LEDGER_TRANSPORT", "hid"),
    )
    try:
        if args.command == "provision":
            cmd_provision(ctx)
        elif args.command == "enroll":
            cmd_enroll(ctx)
        elif args.command == "status":
            cmd_status(ctx)
        elif args.command == "pending":
            cmd_pending(ctx)
        elif args.command == "watch":
            cmd_watch(ctx)
        elif args.command == "approve":
            cmd_approve(ctx, args.ref.upper())
        elif args.command == "decline":
            cmd_decline(ctx, args.ref.upper())
    except ServiceError as error:
        raise SystemExit(str(error)) from None
    except KeyboardInterrupt:
        sys.exit(130)


if __name__ == "__main__":
    main()
